-- Grok Earnings Pulse: one computed snapshot per (event, phase). Written by grok_pulse/pulse.py,
-- read by frontend/app/api/pulse/route.ts (service role; RLS on, no policies).
CREATE TABLE IF NOT EXISTS public.pulse_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker text NOT NULL,
    event_key text NOT NULL,          -- e.g. AAPL-2025-01-30
    phase text NOT NULL CHECK (phase IN ('pre', 'during', 'post')),
    pulse_score numeric,              -- 0..100, 50 = neutral
    source_scores jsonb,              -- {x: {sentiment, n, weight}, articles: {...}, youtube: {...}}
    momentum jsonb,                   -- [{t, minutes_from_call, posts, sentiment, spike}]
    gap jsonb,                        -- expectation vs reality
    brief jsonb,                      -- Grok: {headline, bull_points, bear_points, watch_items, signal, confidence}
    model text,
    generated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (event_key, phase)
);
ALTER TABLE public.pulse_snapshots ENABLE ROW LEVEL SECURITY;
